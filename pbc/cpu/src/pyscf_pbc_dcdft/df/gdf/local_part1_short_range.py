"""Short-range and diffuse-block derivative of GDF GTH local part 1."""

from __future__ import annotations

import numpy as np
from pyscf import lib
from pyscf.pbc.df import aft, ft_ao
from pyscf.pbc.grad import krhf as pyscf_krhf_grad
from pyscf.pbc.tools import pbc as pbc_tools


class ShortRangeLocalPart1:
    """Cache and evaluate the non-Fourier pieces of ``get_pp_loc_part1``.

    ``_RSNucBuilder`` first evaluates a screened three-center nuclear
    attraction integral.  If diffuse-diffuse AO products were removed from
    that real-space integral, PySCF restores them on a small FFT mesh.  This
    class differentiates both operations and the associated short-range
    ``G=0`` overlap correction.
    """

    def __init__(self, builder):
        self.builder = builder
        self.cell = builder.cell
        self.kpts = np.asarray(builder.kpts, dtype=float).reshape(-1, 3)
        self.nkpts = len(self.kpts)
        self.nao = int(self.cell.nao_nr())
        self.fakenuc = aft._fake_nuc(self.cell, with_pseudo=True)
        self.charges = -np.asarray(self.cell.atom_charges(), dtype=float)
        self._ao_slices = np.asarray(self.cell.aoslice_by_atom(), dtype=int)

        self._row_derivative = self._build_row_derivative()
        self._center_derivative = self._build_center_derivative()
        self._nuclear_bar = (
            np.pi
            / float(builder.omega) ** 2
            / float(self.cell.vol)
            * float(self.charges.sum())
        )
        self._diffuse = self._build_diffuse_context()

    def matrix(self, atom_id: int, axis: int) -> np.ndarray:
        """Return the SR plus restored diffuse-block derivative matrix."""

        return self.basis_matrix(atom_id, axis) + self.center_matrix(
            atom_id, axis
        )

    def basis_matrix(self, atom_id: int, axis: int) -> np.ndarray:
        """Return terms generated by translating AO basis functions on A."""

        atom_id, axis = self._indices(atom_id, axis)
        p0, p1 = self._ao_slices[atom_id, 2:]
        row = self._row_derivative[:, axis]
        output = np.zeros(row.shape, dtype=np.complex128)
        output[:, p0:p1, :] -= row[:, p0:p1, :]
        output[:, :, p0:p1] -= row[:, p0:p1, :].transpose(0, 2, 1).conj()
        output -= self._nuclear_bar * self._g0_overlap_derivative(
            atom_id, axis
        )
        output += self._diffuse_basis_derivative(atom_id, axis)
        return output

    def center_matrix(self, atom_id: int, axis: int) -> np.ndarray:
        """Return terms generated by translating pseudopotential center A."""

        atom_id, axis = self._indices(atom_id, axis)
        auxiliary_weights = np.zeros(int(self.fakenuc.nao_nr()))
        q0, q1 = np.asarray(self.fakenuc.aoslice_by_atom(), dtype=int)[
            atom_id, 2:
        ]
        auxiliary_weights[q0:q1] = self.charges[atom_id]
        output = -np.einsum(
            "kdpqz,z->kdpq", self._center_derivative, auxiliary_weights
        )[:, axis].astype(np.complex128, copy=False)
        output += self._diffuse_center_derivative(atom_id, axis)
        return output

    def _build_row_derivative(self) -> np.ndarray:
        values = np.asarray(
            self.builder._int_nuc_vloc(
                self.fakenuc,
                intor="int3c2e_ip1",
                aosym="s1",
                comp=3,
            )
        )
        return values.reshape(self.nkpts, 3, self.nao, self.nao)

    def _build_center_derivative(self) -> np.ndarray:
        kernel = self.builder.gen_int3c_kernel(
            "int3c2e_ip2",
            "s1",
            comp=3,
            j_only=True,
            auxcell=self.fakenuc,
        )
        real, imaginary = kernel()
        values = np.asarray(real) + (
            0.0 if imaginary is None else 1j * np.asarray(imaginary)
        )
        return values.reshape(
            self.nkpts, 3, self.nao, self.nao, self.fakenuc.nao_nr()
        )

    def _g0_overlap_derivative(self, atom_id: int, axis: int) -> np.ndarray:
        """Differentiate the same filtered overlap used by `_RSNucBuilder`."""

        filtered = (
            bool(self.builder.exclude_dd_block)
            and (
                self.cell.dimension == 3
                or (
                    self.cell.dimension == 2
                    and self.cell.low_dim_ft_type != "inf_vacuum"
                )
            )
        )
        if not filtered:
            overlap_rows = np.asarray(
                pyscf_krhf_grad.get_ovlp(self.cell, self.kpts)
            )
            return _full_center_derivative(
                overlap_rows, self._ao_slices, atom_id, axis
            )

        rs_cell = self.builder.rs_cell
        overlap_rows = np.asarray(pyscf_krhf_grad.get_ovlp(rs_cell, self.kpts))
        smooth = rs_cell.get_ao_type() == ft_ao.SMOOTH_BASIS
        smooth_block = smooth[:, None] & smooth[None, :]
        recontract = rs_cell.recontract(dim=2)
        reconstructed = []
        for kpoint in range(self.nkpts):
            row = overlap_rows[kpoint, axis].copy()
            row[smooth_block] = 0
            reconstructed.append(recontract(row))
        reconstructed = np.asarray(reconstructed)
        p0, p1 = self._ao_slices[atom_id, 2:]
        output = np.zeros(
            (self.nkpts, self.nao, self.nao), dtype=reconstructed.dtype
        )
        output[:, p0:p1, :] = reconstructed[:, p0:p1, :]
        return output + output.transpose(0, 2, 1).conj()

    def _build_diffuse_context(self):
        if not bool(self.builder.exclude_dd_block):
            return None
        smooth_cell = self.builder.rs_cell.smooth_basis_cell()
        if smooth_cell.nao == 0 or self.fakenuc.natm == 0:
            return None

        mesh = np.asarray(smooth_cell.mesh, dtype=int)
        gv, gvbase, _weights = self.cell.get_Gv_weights(mesh)
        reciprocal = smooth_cell.reciprocal_vectors()
        gxyz = lib.cartesian_prod([np.arange(len(values)) for values in gvbase])
        auxiliary_ft = ft_ao.ft_ao(
            self.fakenuc, gv, None, reciprocal, gxyz, gvbase
        )
        density_g = np.einsum("a,ga->g", self.charges, auxiliary_ft)
        coulomb_g = pbc_tools.get_coulG(
            self.cell, np.zeros(3), mesh=mesh, Gv=gv
        )
        potential_g = density_g * coulomb_g
        if self.cell.dimension == 3 or (
            self.cell.dimension == 2
            and self.cell.low_dim_ft_type != "inf_vacuum"
        ):
            exponents = np.hstack(self.fakenuc.bas_exps())
            potential_g[0] -= self.charges.dot(np.pi / exponents)
        potential_r = pbc_tools.ifft(potential_g, mesh).real

        coordinates = smooth_cell.get_uniform_grids(mesh)
        evaluator = (
            "GTOval_cart_deriv1" if smooth_cell.cart else "GTOval_sph_deriv1"
        )
        ao_derivative = np.asarray(
            smooth_cell.pbc_eval_gto(evaluator, coordinates, kpts=self.kpts)
        )
        ao_derivative = _normalize_derivative_ao(ao_derivative, self.nkpts)
        ao_value = ao_derivative[:, 0]
        return {
            "cell": smooth_cell,
            "mesh": mesh,
            "gv": gv,
            "auxiliary_ft": auxiliary_ft,
            "potential_r": potential_r,
            "ao_value": ao_value,
            "ao_derivative": ao_derivative[:, 1:4],
            "merge": self.builder.rs_cell.merge_diffused_block("s2"),
        }

    def _diffuse_basis_derivative(self, atom_id: int, axis: int):
        if self._diffuse is None:
            return self._zeros()
        context = self._diffuse
        smooth_cell = context["cell"]
        ao_value = context["ao_value"]
        ao_derivative = context["ao_derivative"][:, axis]
        potential_r = context["potential_r"]
        p0, p1 = np.asarray(smooth_cell.aoslice_by_atom(), dtype=int)[
            atom_id, 2:
        ]
        matrices = np.zeros(
            (self.nkpts, smooth_cell.nao, smooth_cell.nao),
            dtype=np.complex128,
        )
        for kpoint in range(self.nkpts):
            value = ao_value[kpoint]
            derivative = ao_derivative[kpoint]
            matrices[kpoint, p0:p1, :] -= np.dot(
                derivative[:, p0:p1].conj().T * potential_r, value
            )
            matrices[kpoint, :, p0:p1] -= np.dot(
                value.conj().T * potential_r, derivative[:, p0:p1]
            )
        return _merge_diffuse_matrices(
            matrices, context["merge"], self.kpts, self.nao
        )

    def _diffuse_center_derivative(self, atom_id: int, axis: int):
        if self._diffuse is None:
            return self._zeros()
        context = self._diffuse
        q0 = np.asarray(self.fakenuc.aoslice_by_atom(), dtype=int)[atom_id, 2]
        density_derivative_g = (
            self.charges[atom_id]
            * (-1j * context["gv"][:, axis])
            * context["auxiliary_ft"][:, q0]
        )
        coulomb_g = pbc_tools.get_coulG(
            self.cell,
            np.zeros(3),
            mesh=context["mesh"],
            Gv=context["gv"],
        )
        potential_derivative_r = pbc_tools.ifft(
            density_derivative_g * coulomb_g, context["mesh"]
        ).real
        ao_value = context["ao_value"]
        matrices = np.empty(
            (self.nkpts, context["cell"].nao, context["cell"].nao),
            dtype=np.complex128,
        )
        for kpoint in range(self.nkpts):
            value = ao_value[kpoint]
            matrices[kpoint] = np.dot(
                value.conj().T * potential_derivative_r, value
            )
        return _merge_diffuse_matrices(
            matrices, context["merge"], self.kpts, self.nao
        )

    def _zeros(self):
        return np.zeros((self.nkpts, self.nao, self.nao), dtype=np.complex128)

    def _indices(self, atom_id: int, axis: int):
        atom_id = int(atom_id)
        axis = int(axis)
        if not 0 <= atom_id < self.cell.natm:
            raise IndexError(f"atom_id={atom_id} is outside this cell")
        if not 0 <= axis < 3:
            raise IndexError(f"axis={axis} is outside [0, 3)")
        return atom_id, axis


def _full_center_derivative(overlap_rows, ao_slices, atom_id, axis):
    nkpts, _components, nao, _ = overlap_rows.shape
    p0, p1 = ao_slices[atom_id, 2:]
    output = np.zeros((nkpts, nao, nao), dtype=overlap_rows.dtype)
    output[:, p0:p1, :] = overlap_rows[:, axis, p0:p1, :]
    return output + output.transpose(0, 2, 1).conj()


def _normalize_derivative_ao(values: np.ndarray, nkpts: int) -> np.ndarray:
    """Normalize PySCF's Gamma and sampled-k derivative AO layouts."""

    if values.ndim == 3:
        return values[None]
    if values.shape[0] == nkpts:
        return values
    # Some PySCF evaluators return (4,nkpts,ngrid,nao).
    if values.ndim == 4 and values.shape[1] == nkpts:
        return values.transpose(1, 0, 2, 3)
    raise ValueError(f"Unexpected derivative AO shape {values.shape}")


def _merge_diffuse_matrices(matrices, merge, kpts, nao):
    nao_pair = nao * (nao + 1) // 2
    packed = np.zeros((len(kpts), nao_pair), dtype=np.complex128)
    for kpoint, matrix in enumerate(matrices):
        real = packed[kpoint].real.copy()
        imaginary = packed[kpoint].imag.copy()
        merge(real, matrix.real.reshape(matrix.shape + (1,)))
        merge(imaginary, matrix.imag.reshape(matrix.shape + (1,)))
        packed[kpoint] = real + 1j * imaginary
    return np.asarray(
        [
            lib.unpack_tril(value.real)
            if np.linalg.norm(kpt) < 1.0e-10
            else lib.unpack_tril(value)
            for value, kpt in zip(packed, kpts)
        ]
    )
