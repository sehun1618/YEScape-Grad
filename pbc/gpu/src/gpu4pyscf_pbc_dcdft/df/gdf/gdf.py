"""Project-local GPU GDF provider with explicit integral setup ownership.

PySCF and GPU4PySCF currently use different periodic GDF builders.  Both
converge to the same Coulomb operator, but their small finite-factorization
differences can exceed the strict ``1e-8 Ha`` CPU/GPU energy gate.  This
provider offers two deliberately named setup modes. ``native`` uses
GPU4PySCF's CUDA RSDF builder to generate the GDF factors. ``reference``
keeps the original CPU-identical PySCF factors for equation-level parity and
debugging.

This design mirrors a common GPU4PySCF boundary: integral metadata and an
unavailable derivative primitive may originate on the host, while the large
repeated density contractions are device kernels.  It is not a CPU DC-DFT
fallback; source SCF, target PBE, AX/Z-vector, and gradient contractions all
call this provider's CuPy J/K implementation.
"""

from __future__ import annotations

from contextlib import contextmanager
from threading import RLock
from time import perf_counter
from types import MappingProxyType

import cupy as cp
import numpy as np
from gpu4pyscf.lib.cupy_helper import get_avail_mem
from gpu4pyscf.pbc.df import GDF as GPU4PySCFGDF
from gpu4pyscf.pbc.df import df_jk as gpu_df_jk
from gpu4pyscf.pbc.df import rsdf_builder
from gpu4pyscf.pbc.df.fft_jk import _ewald_exxdiv_for_G0
from pyscf.pbc.lib.kpts_helper import is_zero
from pyscf_pbc_dcdft import df as cpu_df
from pyscf_pbc_dcdft.df.gdf.storage import (
    load_cderi_storage,
)
from pyscf_pbc_dcdft.lib.kpoints import normalize_kpts

from .build_signature import make_gdf_build_signature


