class GDF(GPU4PySCFGDF):
    """Periodic GDF with host CDERI setup and device J/K contractions.

    Parameters
    ----------
    cell
        Built periodic PySCF cell.
    kpts
        Cartesian reciprocal vectors in ``1/Bohr``. ``None`` denotes Gamma.
    auxbasis
        Optional auxiliary Gaussian basis accepted by PySCF.
    setup_mode
        ``"native"`` (default) builds CDERI with GPU4PySCF. ``"reference"``
        builds PySCF CDERI on the host and uploads canonical dense blocks.

    Notes
    -----
    ``build()`` always prepares the full k-pair factor set because restricted
    HF and its orbital Hessian require exchange even if a preceding target
    Coulomb call requested J only.
    """

    backend_name = "gdf"
    device_name = "gpu"

    def __init__(
        self,
        cell,
        kpts=None,
        *,
        auxbasis=None,
        setup_mode="native",
    ):
        normalized = normalize_kpts(kpts)
        super().__init__(cell, kpts=normalized)
        self.is_gamma_point = bool(is_zero(normalized))
        if auxbasis is not None:
            self.auxbasis = auxbasis
        self.setup_mode = _validate_setup_mode(setup_mode)
        self._cpu_witness = None
        self._dc_cderi_blocks = None
        self._dc_build_signature = None
        self._dc_pp_cache = {}
        self._dc_pp_cache_hits = 0
        self._dc_pp_cache_misses = 0
        self._dc_pp_build_metadata = None
        self._dc_jk_contraction_metadata = None
        self._dc_jk_profile = None
        self._dc_jk_profile_session = None
        self._dc_native_build_memory_metadata = None
        self._dc_gamma_factorization_metadata = None

    @property
    def uses_native_integrals(self):
        """Whether central GDF factors are generated by GPU4PySCF."""

        return self.setup_mode == "native"

    @property
    def uses_native_jk(self):
        """Whether compressed factors can use GPU4PySCF's native J/K path."""

        return self.uses_native_integrals

    @property
    def cpu_witness(self):
        """Return the built CPU GDF object used only for integral setup."""

        if self.uses_native_integrals:
            raise RuntimeError(
                "native GPU GDF does not create a CPU integral witness"
            )
        self._ensure_built()
        return self._cpu_witness

    @property
    def central_cderi_blocks(self):
        """Return canonical device CDERI factors as a read-only mapping."""

        if self.uses_native_integrals:
            raise RuntimeError(
                "canonical dense CDERI blocks are available only in "
                "setup_mode='reference'"
            )
        self._ensure_built()
        return self._dc_cderi_blocks

    @property
    def gamma_factorization_metadata(self):
        """Return cached native Gamma compression and metric metadata."""

        if not self.uses_native_integrals:
            raise RuntimeError(
                "native Gamma factorization metadata requires "
                "setup_mode='native'"
            )
        self._ensure_built()
        metadata = self._dc_gamma_factorization_metadata
        signature = make_gdf_build_signature(self)
        if metadata is None or metadata.build_signature != signature:
            from .provider_metadata import build_gamma_factorization_metadata

            metadata = build_gamma_factorization_metadata(self)
            self._dc_gamma_factorization_metadata = metadata
        return metadata

    def reset(self, cell=None):
        """Discard host setup and device factors after a geometry change."""

        super().reset(cell)
        self._cpu_witness = None
        self._dc_cderi_blocks = None
        self._dc_build_signature = None
        self._dc_jk_contraction_metadata = None
        self._dc_jk_profile = None
        self._dc_jk_profile_session = None
        self._dc_native_build_memory_metadata = None
        self._dc_gamma_factorization_metadata = None
        self._clear_pp_cache()
        return self

    def build(self, j_only=None, kpts_band=None):
        """Build complete exchange-capable GDF factors in the selected mode."""

        if kpts_band is not None:
            raise NotImplementedError("GDF kpts_band is not supported")
        current_signature = make_gdf_build_signature(self)
        if (
            self._dc_build_signature is not None
            and self._dc_build_signature != current_signature
        ):
            self._clear_pp_cache()
        if self.uses_native_integrals:
            with _bounded_native_build_memory() as memory_metadata:
                self._dc_native_build_memory_metadata = memory_metadata
                GPU4PySCFGDF.build(
                    self,
                    j_only=False,
                    kpts_band=None,
                )
            self._dc_build_signature = make_gdf_build_signature(self)
            return self
        points = np.asarray(self.kpts, dtype=float).reshape(-1, 3)
        witness = self._build_cpu_witness(points)
        storage = load_cderi_storage(witness)
        blocks = {
            pair: cp.asarray(value) for pair, value in storage.blocks.items()
        }
        self._cpu_witness = witness
        self._dc_cderi_blocks = MappingProxyType(blocks)
        # Upstream code commonly checks only whether _cderi is None.  The
        # actual contractions are overridden below and use canonical blocks.
        self._cderi = self._dc_cderi_blocks
        self.auxcell = witness.auxcell
        self.nao = int(self.cell.nao_nr())
        self.kmesh = _infer_kmesh(self.cell, points)
        self._j_only = False
        self._dc_build_signature = make_gdf_build_signature(self)
        return self

    def _build_cpu_witness(self, points):
        """Build the CPU provider whose factors define this GPU backend."""

        witness = cpu_df.GDF(
            self.cell,
            kpts=points,
            auxbasis=self.auxbasis,
        )
        mesh = getattr(self, "mesh", None)
        if mesh is not None:
            witness.mesh = np.asarray(mesh, dtype=int)
        witness.linear_dep_threshold = float(self.linear_dep_threshold)
        witness.build(j_only=False)
        return witness

    def get_naoaux(self):
        """Return the full auxiliary dimension of uploaded CDERI factors."""

        self._ensure_built()
        if self.uses_native_jk:
            return int(GPU4PySCFGDF.get_naoaux(self))
        first = next(iter(self._dc_cderi_blocks.values()))
        return int(first.shape[0])

    def get_pp(self, kpts=None):
        """Return CPU-identical GTH matrices with bounded GPU grid work.

        Native GPU4PySCF local-part-1 selects a reciprocal block from almost
        all currently free VRAM.  CuPy may then require another contiguous
        contraction operand, making large cells fail after the asynchronous
        kernel launch.  Reuse the project-local transactional PP builder that
        RSDF already validates; it changes only the grid execution policy and
        preserves the same GTH decomposition.
        """

        if self.uses_native_integrals:
            # Import lazily to avoid the RSDF-provider/GDF-provider module
            # cycle during package initialization.
            from ..rsdf.pp_value import build_pp_value

            def builder():
                result = build_pp_value(self.cell, kpts)
                self._dc_pp_build_metadata = result.metadata
                return result.value

            return self._cached_pp_value(kpts, builder)
        self._ensure_built()
        return self._cached_pp_value(
            kpts,
            lambda: self._cpu_witness.get_pp(kpts),
        )

    def _cached_pp_value(self, kpts, builder):
        """Cache an immutable PP value while returning mutable copies."""

        key = _kpoint_cache_key(kpts)
        cached = self._dc_pp_cache.get(key)
        if cached is not None:
            self._dc_pp_cache_hits += 1
            return cached.copy()
        value = cp.asarray(builder())
        self._dc_pp_cache[key] = value
        self._dc_pp_cache_misses += 1
        return value.copy()

    def get_nuc(self, kpts=None):
        """Return CPU-identical all-electron nuclear matrices on the device."""

        if self.uses_native_integrals:
            return GPU4PySCFGDF.get_nuc(self, kpts)
        self._ensure_built()
        return cp.asarray(self._cpu_witness.get_nuc(kpts))

    def get_jk(
        self,
        dm,
        hermi=1,
        kpts=None,
        kpts_band=None,
        with_j=True,
        with_k=True,
        omega=None,
        exxdiv=None,
    ):
        """Build periodic J/K from canonical CDERI using CuPy contractions."""

        if omega not in (None, 0, 0.0):
            raise NotImplementedError("range-separated GDF J/K is not supported")
        _validate_kpoints(self.kpts, kpts, kpts_band)
        if not with_j and not with_k:
            return None, None
        self._ensure_built()
        with self._profile_jk_call(
            dm,
            with_j=with_j,
            with_k=with_k,
        ):
            return self._get_jk_built(
                dm,
                hermi=hermi,
                kpts=kpts,
                kpts_band=kpts_band,
                with_j=with_j,
                with_k=with_k,
                omega=omega,
                exxdiv=exxdiv,
            )

    def _get_jk_built(
        self,
        dm,
        *,
        hermi,
        kpts,
        kpts_band,
        with_j,
        with_k,
        omega,
        exxdiv,
    ):
        """Contract J/K after validation and central-factor setup."""

        if self.uses_native_jk:
            density = cp.asarray(dm)
            if self.is_gamma_point and cp.iscomplexobj(density):
                # GPU4PySCF's compressed Gamma kernel accepts float64 only.
                # The J/K maps are real-linear, so preserve a complex
                # transition density with two native real contractions.
                kwargs = {
                    "hermi": hermi,
                    "kpts": kpts,
                    "kpts_band": kpts_band,
                    "with_j": with_j,
                    "with_k": with_k,
                    "omega": omega,
                    "exxdiv": exxdiv,
                }
                real_j, real_k = GPU4PySCFGDF.get_jk(
                    self,
                    density.real,
                    **kwargs,
                )
                imag_j, imag_k = GPU4PySCFGDF.get_jk(
                    self,
                    density.imag,
                    **kwargs,
                )
                return (
                    _combine_real_linear_parts(real_j, imag_j),
                    _combine_real_linear_parts(real_k, imag_k),
                )
            if density.ndim == 4 and not self.is_gamma_point:
                points = np.asarray(self.kpts)
                vj = (
                    gpu_df_jk.get_j_kpts(
                        self,
                        density,
                        hermi=hermi,
                        kpts=points,
                        kpts_band=kpts_band,
                    )
                    if with_j
                    else None
                )
                vk = (
                    gpu_df_jk.get_k_kpts(
                        self,
                        density,
                        hermi=hermi,
                        kpts=points,
                        kpts_band=kpts_band,
                        exxdiv=exxdiv,
                    )
                    if with_k
                    else None
                )
                return vj, vk
            return GPU4PySCFGDF.get_jk(
                self,
                dm,
                hermi=hermi,
                kpts=kpts,
                kpts_band=kpts_band,
                with_j=with_j,
                with_k=with_k,
                omega=omega,
                exxdiv=exxdiv,
            )
        density, input_shape = _format_density(dm, nkpts=len(self.kpts))
        vj = _coulomb_matrices(self._dc_cderi_blocks, density) if with_j else None
        exchange_metadata = {} if with_k else None
        vk = (
            _exchange_matrices(
                self._dc_cderi_blocks,
                density,
                metadata=exchange_metadata,
            )
            if with_k
            else None
        )
        self._dc_jk_contraction_metadata = exchange_metadata
        if vk is not None and exxdiv is not None:
            if exxdiv != "ewald":
                raise NotImplementedError(
                    f"GDF supports exxdiv='ewald' or None, got {exxdiv!r}"
                )
            _ewald_exxdiv_for_G0(
                self.cell,
                np.asarray(self.kpts),
                density,
                vk,
                None,
            )
        if self.is_gamma_point and not cp.iscomplexobj(dm):
            if vj is not None:
                vj = vj.real
            if vk is not None:
                vk = vk.real
        return _restore_shape(vj, input_shape), _restore_shape(vk, input_shape)

    def start_jk_profile(self, *, label="source_hf_scf"):
        """Begin non-synchronizing CUDA-event profiling of logical J/K calls."""

        if self._dc_jk_profile_session is not None:
            raise RuntimeError("a J/K profiling session is already active")
        self._dc_jk_profile = None
        self._dc_jk_profile_session = {
            "label": str(label),
            "central_built_at_start": self._cderi is not None,
            "records": [],
        }

    def finish_jk_profile(self, *, scf_wall_s=None):
        """Resolve a J/K profiling session after the enclosing SCF completes."""

        session = self._dc_jk_profile_session
        if session is None:
            return self._dc_jk_profile
        self._dc_jk_profile_session = None
        records = session["records"]
        for record in records:
            record["device_s"] = float(
                cp.cuda.get_elapsed_time(
                    record.pop("start_event"),
                    record.pop("end_event"),
                )
                / 1000.0
            )
        central_build_s = self._profile_central_build_seconds(session)
        device_total_s = sum(record["device_s"] for record in records)
        host_dispatch_total_s = sum(
            record["host_dispatch_s"] for record in records
        )
        profile = {
            "label": session["label"],
            "central_build_was_new": bool(
                not session["central_built_at_start"] and self._cderi is not None
            ),
            "central_build_s": central_build_s,
            "logical_call_count": len(records),
            "device_total_s": float(device_total_s),
            "first_call_device_s": (
                None if not records else float(records[0]["device_s"])
            ),
            "repeated_call_device_s": float(
                sum(record["device_s"] for record in records[1:])
            ),
            "host_dispatch_total_s": float(host_dispatch_total_s),
            "calls": records,
        }
        if scf_wall_s is not None:
            profile["scf_wall_s"] = float(scf_wall_s)
            profile["wall_remainder_after_central_and_jk_s"] = float(
                max(0.0, float(scf_wall_s) - central_build_s - device_total_s)
            )
        self._dc_jk_profile = profile
        return profile

    @contextmanager
    def _profile_jk_call(self, dm, *, with_j, with_k):
        session = self._dc_jk_profile_session
        if session is None:
            yield
            return
        start_event = cp.cuda.Event()
        end_event = cp.cuda.Event()
        start_event.record()
        host_start = perf_counter()
        try:
            yield
        finally:
            host_dispatch_s = perf_counter() - host_start
            end_event.record()
            density = cp.asarray(dm)
            session["records"].append(
                {
                    "index": len(session["records"]),
                    "with_j": bool(with_j),
                    "with_k": bool(with_k),
                    "shape": [int(value) for value in density.shape],
                    "dtype": str(density.dtype),
                    "complex_gamma_split": bool(
                        self.is_gamma_point and cp.iscomplexobj(density)
                    ),
                    "host_dispatch_s": float(host_dispatch_s),
                    "start_event": start_event,
                    "end_event": end_event,
                }
            )

    def _profile_central_build_seconds(self, session):
        if session["central_built_at_start"]:
            return 0.0
        metadata = getattr(self, "_dc_central_build_metadata", None)
        if not isinstance(metadata, dict):
            return 0.0
        return float(metadata.get("total_build_seconds", 0.0))

    def get_j_e1(self, dm, kpts=None):
        """Return the native GPU GDF Coulomb-energy nuclear derivative."""

        from .contracted_derivative import coulomb_energy_derivative

        _validate_kpoints(self.kpts, kpts, None)
        return coulomb_energy_derivative(self, dm)

    def get_k_e1(self, dm, kpts=None, exxdiv="ewald"):
        """Return the positive native GPU GDF exchange-energy derivative."""

        from .contracted_derivative import exchange_energy_derivative

        _validate_kpoints(self.kpts, kpts, None)
        return exchange_energy_derivative(self, dm, exxdiv=exxdiv)

    def get_hf_e1(self, dm, kpts=None, exxdiv="ewald"):
        """Return the restricted ``J-K/2`` energy nuclear derivative."""

        from .contracted_derivative import restricted_hf_energy_derivative

        _validate_kpoints(self.kpts, kpts, None)
        return restricted_hf_energy_derivative(
            self,
            dm,
            exxdiv=exxdiv,
        )

    def capability(self) -> dict[str, object]:
        """Return the currently validated GPU GDF feature contract."""

        return {
            "backend": self.backend_name,
            "device": self.device_name,
            "auxbasis": self.auxbasis,
            "energy": True,
            "analytic_gradient": True,
            "gradient_status": "stage_5_completion_gate_passed",
            "target_xc": ["PBE", "SCAN", "R2SCAN"],
            "gdf_setup_mode": self.setup_mode,
            "central_cderi": (
                "GPU4PySCF CUDA RSDF builder"
                if self.uses_native_integrals
                else "PySCF host setup, canonical CuPy storage"
            ),
            "jk_contraction": (
                "GPU4PySCF CuPy/CUDA"
                if self.uses_native_integrals
                else "project-local CuPy"
            ),
            "silent_cpu_fallback": False,
            "jk_contraction_metadata": self._dc_jk_contraction_metadata,
            "jk_profile": self._dc_jk_profile,
            "native_cderi_build_memory": getattr(
                self,
                "_dc_native_build_memory_metadata",
                None,
            ),
            "gamma_factorization_metadata": (
                None
                if self._dc_gamma_factorization_metadata is None
                else self._dc_gamma_factorization_metadata.summary()
            ),
            "pseudopotential_value_cache": {
                "builder": "project-local bounded GPU4PySCF PP",
                "hits": int(self._dc_pp_cache_hits),
                "misses": int(self._dc_pp_cache_misses),
                "build_metadata": self._dc_pp_build_metadata,
            },
            "host_boundaries": self._host_boundaries(),
        }

    def to_cpu(self):
        """Create the matching project-local CPU GDF provider."""

        return cpu_df.GDF(
            self.cell,
            kpts=np.asarray(self.kpts),
            auxbasis=self.auxbasis,
        )

    def _ensure_built(self):
        current = make_gdf_build_signature(self)
        if self._cderi is not None and self._dc_build_signature != current:
            self._discard_cached_build()
        if self._cderi is None:
            self.build(j_only=False)

    def _discard_cached_build(self):
        """Drop factors whose ownership signature no longer matches."""

        GPU4PySCFGDF.reset(self)
        self._cpu_witness = None
        self._dc_cderi_blocks = None
        self._dc_build_signature = None
        self._dc_jk_contraction_metadata = None
        self._dc_jk_profile = None
        self._dc_jk_profile_session = None
        self._dc_native_build_memory_metadata = None
        self._dc_gamma_factorization_metadata = None
        self._clear_pp_cache()

    def _clear_pp_cache(self):
        """Discard geometry-dependent pseudopotential value matrices."""

        self._dc_pp_cache.clear()
        self._dc_pp_cache_hits = 0
        self._dc_pp_cache_misses = 0
        self._dc_pp_build_metadata = None

    def _host_boundaries(self):
        boundaries = ["PySCF Cell/AuxCell metadata"]
        if not self.uses_native_integrals:
            boundaries.extend(
                [
                    "central 2-center/3-center integral and CDERI setup",
                    "central GDF local/nonlocal pseudopotential matrix setup",
                    "GDF derivative primitive and GTH H1 generation",
                ]
            )
        else:
            boundaries.extend(
                [
                    "GPU4PySCF mapped-host CDERI storage and bookkeeping",
                    "GDF local-part-2 pseudopotential setup",
                    "GDF local-part-2 analytic H1 primitive generation",
                ]
            )
        return boundaries


def _combine_real_linear_parts(real_part, imaginary_part):
    """Reconstruct a complex J/K result from two real native calls."""

    if real_part is None:
        if imaginary_part is not None:
            raise RuntimeError("native J/K returned inconsistent optional parts")
        return None
    if imaginary_part is None:
        raise RuntimeError("native J/K returned inconsistent optional parts")
    return real_part + 1j * imaginary_part


def _format_density(dm, *, nkpts):
    value = cp.asarray(dm)
    input_shape = value.shape
    nao = value.shape[-1]
    if value.shape[-2:] != (nao, nao):
        raise ValueError(f"density matrices must be square, got {value.shape}")
    if nkpts == 1:
        if value.ndim == 2:
            return value.reshape(1, 1, nao, nao), input_shape
        if value.ndim == 3:
            return value.reshape(-1, 1, nao, nao), input_shape
    else:
        if value.ndim == 3 and value.shape[0] == nkpts:
            return value.reshape(1, nkpts, nao, nao), input_shape
        if value.ndim == 4 and value.shape[1] == nkpts:
            return value, input_shape
    raise ValueError(
        f"density shape {value.shape} is incompatible with {nkpts} k-points"
    )


def _restore_shape(value, shape):
    return None if value is None else value.reshape(shape)


def _coulomb_matrices(blocks, density):
    nset, nkpts, nao, _ = density.shape
    naux = next(iter(blocks.values())).shape[0]
    output = cp.zeros((nset, nkpts, nao, nao), dtype=cp.complex128)
    for set_id in range(nset):
        jaux = cp.zeros(naux, dtype=cp.complex128)
        for k_id in range(nkpts):
            jaux += cp.einsum(
                "pij,ji->p",
                _device_pair_block(blocks, k_id, k_id),
                density[set_id, k_id],
            )
        for k_id in range(nkpts):
            output[set_id, k_id] = cp.einsum(
                "p,pij->ij", jaux, _device_pair_block(blocks, k_id, k_id)
            ) / nkpts
    return output


def _exchange_matrices(blocks, density, *, metadata=None):
    nset, nkpts, nao, _ = density.shape
    output = cp.zeros((nset, nkpts, nao, nao), dtype=cp.complex128)
    pair_metadata = []
    for set_id in range(nset):
        for ki in range(nkpts):
            for kj in range(nkpts):
                left = _device_pair_block(blocks, ki, kj)
                right = _device_pair_block(blocks, kj, ki)
                contribution, execution = _blocked_exchange_pair(
                    left,
                    density[set_id, kj],
                    right,
                )
                output[set_id, ki] += contribution / nkpts
                execution.update(
                    {
                        "density_set": int(set_id),
                        "ki": int(ki),
                        "kj": int(kj),
                    }
                )
                pair_metadata.append(execution)
    if metadata is not None:
        metadata.clear()
        metadata.update(
            {
                "algorithm": "bounded_auxiliary_batched_matmul",
                "pair_executions": pair_metadata,
                "silent_cpu_fallback": False,
            }
        )
    return output


def _blocked_exchange_pair(left, density, right):
    """Contract one CDERI pair with bounded auxiliary-axis workspaces."""

    naux, nao, nao_right = left.shape
    if nao != nao_right or right.shape != (naux, nao, nao):
        raise ValueError(
            "exchange CDERI pair dimensions are inconsistent: "
            f"left={left.shape}, right={right.shape}"
        )
    if density.shape != (nao, nao):
        raise ValueError(
            f"exchange density must have shape {(nao, nao)}, got {density.shape}"
        )
    plan = _plan_exchange_auxiliary_blocks(
        naux,
        nao,
        np.result_type(left.dtype, density.dtype, right.dtype),
        free_device_bytes=int(get_avail_mem(exclude_memory_pool=True)),
    )
    result = cp.zeros((nao, nao), dtype=cp.complex128)
    start = 0
    block_size = plan["initial_block_size"]
    minimum_block_size = block_size
    block_count = 0
    rebatch_count = 0
    while start < naux:
        stop = min(naux, start + block_size)
        try:
            intermediate = cp.matmul(left[start:stop], density)
            product = cp.matmul(intermediate, right[start:stop])
            result += product.sum(axis=0)
        except Exception as error:
            if not _is_gpu_out_of_memory(error):
                raise
            intermediate = product = None
            _release_unused_gpu_memory()
            attempted = stop - start
            if attempted <= 1:
                raise MemoryError(
                    "GPU memory is insufficient for one auxiliary exchange "
                    "slice"
                ) from error
            block_size = max(1, attempted // 2)
            minimum_block_size = min(minimum_block_size, block_size)
            rebatch_count += 1
            continue
        intermediate = product = None
        minimum_block_size = min(minimum_block_size, stop - start)
        block_count += 1
        start = stop
    execution = {
        **plan,
        "final_block_size": int(block_size),
        "minimum_block_size": int(minimum_block_size),
        "block_count": int(block_count),
        "rebatch_count": int(rebatch_count),
        "completed_auxiliary_count": int(naux),
    }
    return result, execution


def _plan_exchange_auxiliary_blocks(
    naux,
    nao,
    dtype,
    *,
    free_device_bytes,
    memory_fraction=_EXCHANGE_MEMORY_FRACTION,
    minimum_reserve_bytes=_EXCHANGE_MINIMUM_RESERVE_BYTES,
    maximum_block_size=_EXCHANGE_MAX_AUX_BLOCK,
):
    """Plan a conservative auxiliary block for two batched GEMM workspaces."""

    naux = int(naux)
    nao = int(nao)
    free_device_bytes = int(free_device_bytes)
    itemsize = int(np.dtype(dtype).itemsize)
    if naux <= 0 or nao <= 0:
        raise ValueError("exchange dimensions must be positive")
    if not 0.0 < float(memory_fraction) <= 1.0:
        raise ValueError("exchange memory_fraction must be in (0, 1]")
    reserve = min(int(minimum_reserve_bytes), free_device_bytes // 2)
    budget = min(
        int(free_device_bytes * float(memory_fraction)),
        max(0, free_device_bytes - reserve),
    )
    # Two explicit batched GEMM outputs are live.  Two additional planes
    # conservatively cover contiguous copies selected by CuPy/cuBLAS.
    bytes_per_auxiliary = 4 * nao * nao * itemsize
    block_size = max(1, budget // max(1, bytes_per_auxiliary))
    block_size = min(naux, int(maximum_block_size), int(block_size))
    return {
        "naux": naux,
        "nao": nao,
        "dtype": str(np.dtype(dtype)),
        "free_device_bytes_at_plan": free_device_bytes,
        "memory_fraction": float(memory_fraction),
        "reserve_bytes": int(reserve),
        "budget_bytes": int(budget),
        "bytes_per_auxiliary": int(bytes_per_auxiliary),
        "estimated_block_working_bytes": int(
            block_size * bytes_per_auxiliary
        ),
        "initial_block_size": int(block_size),
        "maximum_block_size": int(maximum_block_size),
    }


def _is_gpu_out_of_memory(error):
    if isinstance(error, cp.cuda.memory.OutOfMemoryError):
        return True
    name = type(error).__name__.lower()
    message = str(error).lower()
    return (
        "outofmemory" in name
        or "memoryallocation" in message
        or "out of memory" in message
    )


def _release_unused_gpu_memory():
    cp.get_default_memory_pool().free_all_blocks()
    pinned = cp.get_default_pinned_memory_pool()
    if pinned is not None:
        pinned.free_all_blocks()


def _device_pair_block(blocks, ki, kj):
    key = (int(ki), int(kj))
    if key in blocks:
        return blocks[key]
    reverse = (key[1], key[0])
    if reverse in blocks:
        return blocks[reverse].conj().transpose(0, 2, 1)
    raise KeyError(f"CDERI block for pair {key} is unavailable")


def _validate_kpoints(provider_kpts, kpts, kpts_band):
    reference = np.asarray(provider_kpts, dtype=float).reshape(-1, 3)
    if kpts is not None:
        requested = np.asarray(kpts, dtype=float).reshape(-1, 3)
        if requested.shape != reference.shape or not np.allclose(
            requested, reference, atol=1.0e-10, rtol=0.0
        ):
            raise NotImplementedError("GDF J/K requires the provider k-point set")
    if kpts_band is not None:
        band = np.asarray(kpts_band, dtype=float).reshape(-1, 3)
        if band.shape != reference.shape or not np.allclose(
            band, reference, atol=1.0e-10, rtol=0.0
        ):
            raise NotImplementedError("GDF kpts_band is not supported")


def _kpoint_cache_key(kpts):
    if kpts is None:
        return ("default",)
    points = np.asarray(kpts, dtype=float)
    return ("explicit", points.shape, points.tobytes())


def _infer_kmesh(cell, kpts):
    if len(kpts) == 1:
        return np.ones(3, dtype=int)
    from gpu4pyscf.pbc.tools.k2gamma import kpts_to_kmesh

    return np.asarray(kpts_to_kmesh(cell, kpts), dtype=int)


@contextmanager
def _bounded_native_build_memory():
    """Bound upstream planning and retain CPU-equivalent metric algebra."""

    metadata = {
        "max_reported_free_device_bytes": int(
            _NATIVE_BUILD_REPORTED_FREE_BYTES
        ),
        "actual_free_device_bytes": None,
        "reported_free_device_bytes": None,
    }
    with _NATIVE_BUILD_ADAPTER_LOCK:
        original = rsdf_builder.get_avail_mem
        original_prefer_ed = rsdf_builder.PREFER_ED

        def bounded_available_memory(exclude_memory_pool=True):
            actual = int(
                original(exclude_memory_pool=exclude_memory_pool)
            )
            reported = min(actual, _NATIVE_BUILD_REPORTED_FREE_BYTES)
            metadata["actual_free_device_bytes"] = actual
            metadata["reported_free_device_bytes"] = int(reported)
            return int(reported)

        rsdf_builder.get_avail_mem = bounded_available_memory
        # GPU4PySCF 1.8 changed the periodic GDF default to ED.  The local
        # derivative factorization and strict CPU/GPU parity contract require
        # the same Cholesky metric representation used by PySCF GDF/RSDF.
        rsdf_builder.PREFER_ED = False
        try:
            yield metadata
        finally:
            rsdf_builder.get_avail_mem = original
            rsdf_builder.PREFER_ED = original_prefer_ed


def _validate_setup_mode(value):
    mode = str(value).strip().lower()
    if mode not in {"native", "reference"}:
        raise ValueError(
            "GDF setup_mode must be 'native' or 'reference', "
            f"got {value!r}"
        )
    return mode
