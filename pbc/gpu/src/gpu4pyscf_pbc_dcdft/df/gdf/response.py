"""Analytic GDF source/metric response with device-side linear algebra.

Periodic 2-center and 3-center derivative integrals are generated by the
PySCF CPU integral engine because GPU4PySCF does not currently expose their
nuclear derivatives.  This boundary is explicit and timed.  Cholesky
factorization, metric-square-root response, ``dCDERI`` assembly, and all later
J/K contractions remain on the active CuPy device.
"""

from __future__ import annotations

from dataclasses import dataclass
from time import perf_counter
from types import MappingProxyType
from typing import Mapping

import cupy as cp
import numpy as np
from pyscf_pbc_dcdft.df.gdf.metric import (
    auxiliary_metric,
    auxiliary_metric_derivative,
)
from pyscf_pbc_dcdft.df.gdf.pair_response import (
    RSGDFParameters,
    rsgdf_parameters,
)
from pyscf_pbc_dcdft.df.gdf.source import (
    three_center_source,
    three_center_source_derivative,
)
from pyscf_pbc_dcdft.df.gdf.storage import (
    Pair,
    canonical_pairs,
)

from .cholesky import CDERIFactorization


@dataclass(frozen=True)
class GDFResponseTensors:
    """Device CDERI values and analytic derivatives for canonical k-pairs."""

    cderi: Mapping[Pair, cp.ndarray]
    dcderi: Mapping[Pair, cp.ndarray]
    source_dcderi: Mapping[Pair, cp.ndarray]
    metric_dcderi: Mapping[Pair, cp.ndarray]
    parameters: RSGDFParameters
    value_parity_max_abs: float
    host_primitive_seconds: float
    device_response_seconds: float


def build_gdf_response_tensors(
    provider,
    *,
    value_tolerance: float = 1.0e-7,
) -> GDFResponseTensors:
    """Build analytic ``dCDERI`` while keeping response algebra on the GPU.

    Parameters
    ----------
    provider
        Built project-local GPU :class:`GDF` provider.
    value_tolerance
        Maximum allowed difference between reconstructed central CDERI and a
        matching project-local CPU GDF storage block.  This protects omega,
        mesh, auxiliary-basis, pair orientation, and Cholesky conventions.

    Returns
    -------
    GDFResponseTensors
        CuPy mappings with canonical ``(ki, kj)``, ``ki >= kj`` keys.

    Notes
    -----
    The CPU provider created here is a value/convention witness and an
    integral source.  It never evaluates a DC-DFT gradient.  The returned
    ``dCDERI`` and every downstream contraction are device arrays.
    """

    if getattr(provider, "backend_name", None) != "gdf":
        raise TypeError("build_gdf_response_tensors requires GPU GDF")
    if getattr(provider, "_cderi", None) is None:
        provider.build(j_only=False)

    kpts = np.asarray(provider.kpts, dtype=float).reshape(-1, 3)
    host_start = perf_counter()
    witness = provider.cpu_witness
    central_blocks = provider.central_cderi_blocks
    parameters = rsgdf_parameters(
        witness.cell,
        witness.auxcell,
        kpts,
        source_mesh=getattr(witness, "mesh", None),
        linear_dep_threshold=float(witness.linear_dep_threshold),
    )

    primitive_blocks = {}
    for pair in canonical_pairs(len(kpts)):
        primitive_blocks[pair] = _host_pair_primitives(
            witness.cell,
            witness.auxcell,
            kpts,
            pair,
            parameters,
        )
    host_seconds = perf_counter() - host_start

    device_start = perf_counter()
    values = {}
    derivatives = {}
    source_parts = {}
    metric_parts = {}
    parity = 0.0
    for pair, primitives in primitive_blocks.items():
        value, total, source_part, metric_part = _device_pair_response(
            primitives, nao=int(provider.cell.nao_nr())
        )
        values[pair] = value
        derivatives[pair] = total
        source_parts[pair] = source_part
        metric_parts[pair] = metric_part
        gap = cp.max(cp.abs(value - central_blocks[pair]))
        parity = max(parity, float(gap.get()))
    cp.cuda.Stream.null.synchronize()
    device_seconds = perf_counter() - device_start
    if parity > float(value_tolerance):
        raise RuntimeError(
            "GPU GDF source/metric convention does not reproduce CPU CDERI "
            f"storage: max gap {parity:.3e} > {float(value_tolerance):.3e}"
        )
    return GDFResponseTensors(
        cderi=MappingProxyType(values),
        dcderi=MappingProxyType(derivatives),
        source_dcderi=MappingProxyType(source_parts),
        metric_dcderi=MappingProxyType(metric_parts),
        parameters=parameters,
        value_parity_max_abs=parity,
        host_primitive_seconds=host_seconds,
        device_response_seconds=device_seconds,
    )


def _host_pair_primitives(cell, auxcell, kpts, pair, parameters):
    ki, kj = pair
    first = kpts[ki]
    second = kpts[kj]
    momentum_transfer = second - first
    source = three_center_source(
        cell,
        auxcell,
        parameters.omega,
        mesh=parameters.source_mesh,
        kpti=first,
        kptj=second,
    )
    metric = auxiliary_metric(
        cell,
        auxcell,
        parameters.omega,
        mesh=parameters.metric_mesh,
        q=momentum_transfer,
    )
    source_derivatives = []
    metric_derivatives = []
    for atom_id in range(cell.natm):
        source_derivatives.append(
            three_center_source_derivative(
                cell,
                auxcell,
                atom_id,
                parameters.omega,
                mesh=parameters.source_mesh,
                kpti=first,
                kptj=second,
            ).total
        )
        metric_derivatives.append(
            auxiliary_metric_derivative(
                cell,
                auxcell,
                atom_id,
                parameters.omega,
                mesh=parameters.metric_mesh,
                q=momentum_transfer,
            ).total
        )
    return (
        np.asarray(source),
        np.asarray(metric),
        np.asarray(source_derivatives),
        np.asarray(metric_derivatives),
    )


def _device_pair_response(primitives, *, nao):
    source, metric, source_derivatives, metric_derivatives = primitives
    factorization = CDERIFactorization.build(
        cp.asarray(source), cp.asarray(metric), nao=nao
    )
    natm = source_derivatives.shape[0]
    naux = factorization.value.shape[0]
    shape = (natm, 3, naux, nao, nao)
    total = cp.empty(shape, dtype=cp.complex128)
    source_part = cp.empty_like(total)
    metric_part = cp.empty_like(total)
    for atom_id in range(natm):
        d_source = cp.asarray(source_derivatives[atom_id])
        d_metric = cp.asarray(metric_derivatives[atom_id])
        for axis in range(3):
            response = factorization.differentiate(
                d_source[axis], d_metric[axis]
            )
            source_part[atom_id, axis] = response.source
            metric_part[atom_id, axis] = response.metric
            total[atom_id, axis] = response.total
    return factorization.value, total, source_part, metric_part
