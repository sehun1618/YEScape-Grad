"""Device-resident GDF metric factorization and analytic response.

For one momentum-transfer block, periodic GDF uses

``C = L^{-1} B`` and ``M = L L^H``.

``B`` and ``M`` are generated by periodic integral engines.  Once copied to
the device, this module owns the Cholesky factorization, triangular solves,
metric-square-root response, and ``dCDERI`` assembly in CuPy.  No finite
difference or CPU DC-DFT gradient is called here.
"""

from __future__ import annotations

from dataclasses import dataclass

import cupy as cp
from cupyx.scipy.linalg import solve_triangular


@dataclass(frozen=True)
class CDERIDerivativeParts:
    """Device CDERI value and separated source/metric derivatives."""

    value: cp.ndarray
    source: cp.ndarray
    metric: cp.ndarray

    @property
    def total(self) -> cp.ndarray:
        """Return ``dC = dC_source + dC_metric`` on the device."""

        return self.source + self.metric


@dataclass(frozen=True)
class CDERIFactorization:
    """Reusable device factorization for one GDF k-point pair."""

    factor: cp.ndarray
    value: cp.ndarray
    nao: int

    @classmethod
    def build(cls, source, metric, *, nao: int):
        """Factor ``M`` and solve ``C=L^-1 B`` on the active device."""

        metric_array = _square_metric(metric)
        source_array = _source_matrix(source, nao=int(nao))
        # cupyx.solve_triangular chooses its output dtype from the factor and
        # would otherwise cast a complex Gamma source through a real metric.
        # Promoting both operands preserves tiny imaginary parts and is also
        # the required dtype for general momentum-transfer blocks.
        dtype = cp.result_type(metric_array.dtype, source_array.dtype)
        metric_array = metric_array.astype(dtype, copy=False)
        source_array = source_array.astype(dtype, copy=False)
        factor = cp.linalg.cholesky(metric_array)
        solved = solve_triangular(
            factor, source_array.T, lower=True, check_finite=False
        )
        value = solved.reshape(solved.shape[0], int(nao), int(nao))
        return cls(factor=factor, value=value, nao=int(nao))

    def astype(self, dtype):
        """Return this factorization in a solve-safe common dtype."""

        target = cp.dtype(dtype)
        if self.factor.dtype == target and self.value.dtype == target:
            return self
        return CDERIFactorization(
            factor=self.factor.astype(target, copy=False),
            value=self.value.astype(target, copy=False),
            nao=self.nao,
        )

    def differentiate(self, source_derivative, metric_derivative):
        """Return source and metric contributions to one Cartesian ``dC``."""

        d_source = _source_matrix(source_derivative, nao=self.nao)
        d_metric = _square_metric(metric_derivative)
        dtype = cp.result_type(
            self.factor.dtype,
            self.value.dtype,
            d_source.dtype,
            d_metric.dtype,
        )
        working = self.astype(dtype)
        d_source = d_source.astype(dtype, copy=False)
        d_metric = d_metric.astype(dtype, copy=False)
        source_solved = solve_triangular(
            working.factor, d_source.T, lower=True, check_finite=False
        ).reshape(working.value.shape)
        d_factor = _differentiate_cholesky(
            working.factor, d_metric
        )
        value_flat = working.value.reshape(working.value.shape[0], -1)
        metric_rhs = -(d_factor @ value_flat)
        metric_solved = solve_triangular(
            working.factor, metric_rhs, lower=True, check_finite=False
        ).reshape(working.value.shape)
        return CDERIDerivativeParts(
            value=working.value,
            source=source_solved,
            metric=metric_solved,
        )


def _differentiate_cholesky(factor, metric_derivative):
    """Differentiate ``M=L L^H`` in the lower-triangular Cholesky gauge."""

    factor_array = cp.asarray(factor)
    derivative_array = _square_metric(metric_derivative)
    dtype = cp.result_type(factor_array.dtype, derivative_array.dtype)
    factor_array = factor_array.astype(dtype, copy=False)
    derivative_array = derivative_array.astype(dtype, copy=False)
    left_solved = solve_triangular(
        factor_array, derivative_array, lower=True, check_finite=False
    )
    reduced = solve_triangular(
        factor_array.conj(), left_solved.T, lower=True, check_finite=False
    ).T
    gauge = cp.tril(reduced, k=-1)
    diagonal = 0.5 * cp.diag(reduced).real
    gauge += cp.diag(diagonal)
    return factor_array @ gauge


def _square_metric(value):
    array = cp.asarray(value)
    if array.ndim != 2 or array.shape[0] != array.shape[1]:
        raise ValueError(f"metric must be square, got {array.shape}")
    return array


def _source_matrix(value, *, nao: int):
    array = cp.asarray(value)
    expected = int(nao) ** 2
    if array.ndim != 2 or array.shape[0] != expected:
        raise ValueError(
            f"source must have shape ({expected}, naux), got {array.shape}"
        )
    return array
